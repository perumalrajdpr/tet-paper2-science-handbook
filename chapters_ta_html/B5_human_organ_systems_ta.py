def build_pdf(out_pdf_path, out_html_path=None):
    fragments = content()
    css_rel = os.path.relpath(CSS_FILE_ABS, HERE)
    html_str = assemble_html(
        title=f'{CHAPTER_ID} · {CHAPTER_TITLE}',
        css_path=css_rel,
        body_fragments=fragments,
    )
    if out_html_path:
        Path(out_html_path).write_text(html_str, encoding='utf-8')

    chapter_css_override = """
        .rapid     { page-break-inside: auto !important; break-inside: auto !important; }
        .rapid thead { display: table-header-group; }
        .rapid tr  { page-break-inside: avoid; break-inside: avoid; }
        .grid      { page-break-inside: auto !important; break-inside: auto !important; }
        .grid thead { display: table-header-group; }
        .grid tr   { page-break-inside: avoid; break-inside: avoid; }
        .oneliners { page-break-inside: auto !important; break-inside: auto !important; }
        .oneliners > * { page-break-inside: avoid; break-inside: avoid; }
    """

    HTML(string=html_str, base_url=str(HERE)).write_pdf(
        out_pdf_path,
        stylesheets=[
            CSS(filename=str(CSS_FILE_ABS)),
            CSS(string=chapter_css_override),
        ],
        optimize_size=(),
    )
    return out_pdf_path


